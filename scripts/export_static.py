"""Write the files the static (server-less) site needs into web/public/ and web/src/lib/:

  web/public/info.json          what GET /api/info returns, plus the browser model's file/sha
  web/public/figures/*.png      the notebook figures GET /api/figures/{name} serves
  web/src/lib/jetLut.ts         OpenCV's COLORMAP_JET as a 256-entry RGB table (Grad-CAM colours)

Run after scripts/export_onnx.py, and again whenever deployment_artifacts/ changes.
"""
import json
import shutil
import sys
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.artifacts import load_artifacts  # noqa: E402
from app.main import build_info  # noqa: E402
from app.settings import Settings  # noqa: E402

PUBLIC = ROOT / "web/public"


def main():
    settings = Settings.from_env()
    art = load_artifacts(settings)
    info = build_info(art)
    info["limits"] = {"max_upload_mb": settings.max_upload_mb, "formats": ["PNG", "JPEG", "TIFF", "BMP"]}

    meta_path = PUBLIC / "model/model_meta.json"
    if not meta_path.is_file():
        sys.exit("Run scripts/export_onnx.py first.")
    meta = json.loads(meta_path.read_text())
    if meta["source_weights_sha256"] != art.config["model"]["weights_sha256"]:
        sys.exit("The ONNX model was exported from different weights; re-run scripts/export_onnx.py.")
    info["browser_model"] = {"url": f"/model/{meta['file']}", "sha256": meta["sha256"], "bytes": meta["bytes"],
                             "parity": meta["parity"]}
    info["decision"] = {"near_threshold_margin": 0.05, "aspect_tolerance": 0.02, "max_pixels": 40_000_000,
                        "overlay_image_weight": 0.6, "size_hw": art.config["preprocessing"]["resize"]["size_hw"]}
    (PUBLIC / "info.json").write_text(json.dumps(info, indent=1))

    fig_dir = PUBLIC / "figures"
    fig_dir.mkdir(exist_ok=True)
    for name, path in art.figures.items():
        shutil.copyfile(path, fig_dir / name)

    lut = cv2.cvtColor(cv2.applyColorMap(np.arange(256, dtype=np.uint8)[:, None], cv2.COLORMAP_JET),
                       cv2.COLOR_BGR2RGB).reshape(-1).tolist()
    (ROOT / "web/src/lib/jetLut.ts").write_text(
        "// Generated by scripts/export_static.py from cv2.applyColorMap(..., COLORMAP_JET), RGB order.\n"
        f"export const JET_LUT = new Uint8Array({json.dumps(lut, separators=(',', ':'))});\n")
    print("wrote info.json, figures:", sorted(art.figures), "and jetLut.ts")


if __name__ == "__main__":
    main()
